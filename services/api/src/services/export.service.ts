import { Review, Finding, SeverityCounts } from '../types/index.js';

export class ExportService {
  static formatMarkdown(review: Review, findings: Finding[], counts: SeverityCounts): string {
    const timestamp = review.created_at ? new Date(review.created_at).toUTCString() : '';
    let md = `# CodeMind AI — Security & Code Quality Audit Report\n\n`;
    md += `**Review Title:** ${review.title}  \n`;
    md += `**Review ID:** \`${review.id}\`  \n`;
    md += `**Language:** ${review.language}  \n`;
    md += `**Status:** ${review.status.toUpperCase()}  \n`;
    md += `**Date:** ${timestamp}  \n`;
    md += `**Provider/Model:** ${review.provider} / ${review.model}  \n\n`;

    md += `## Executive Summary\n\n`;
    md += `${review.summary || 'No summary provided.'}\n\n`;

    md += `### Severity Distribution\n\n`;
    md += `| Critical | High | Medium | Low | Info |\n`;
    md += `| :---: | :---: | :---: | :---: | :---: |\n`;
    md += `| **${counts.critical}** | **${counts.high}** | **${counts.medium}** | **${counts.low}** | **${counts.info}** |\n\n`;

    md += `## Detailed Findings\n\n`;
    if (findings.length === 0) {
      md += `*No findings identified for this review.*\n`;
    } else {
      findings.forEach((f, idx) => {
        md += `### ${idx + 1}. [${f.severity.toUpperCase()}] ${f.title}\n\n`;
        md += `- **Agent:** \`${f.agent_name}\`  \n`;
        md += `- **Category:** \`${f.category}\`  \n`;
        md += `- **Confidence:** \`${(f.confidence * 100).toFixed(0)}%\`  \n`;
        if (f.cwe) md += `- **CWE:** \`${f.cwe}\`  \n`;
        if (f.file_path) md += `- **Location:** \`${f.file_path}\` (Lines ${f.start_line ?? '?'}-${f.end_line ?? '?'})  \n`;
        md += `\n**Description:**  \n${f.description || 'N/A'}\n\n`;
        md += `**Impact:**  \n${f.impact || 'N/A'}\n\n`;
        md += `**Recommendation:**  \n${f.recommendation || 'N/A'}\n\n`;
        if (f.evidence) {
          md += `**Evidence:**  \n\`\`\`\n${f.evidence}\n\`\`\`\n\n`;
        }
        if (f.code_snippet) {
          md += `**Code Snippet:**  \n\`\`\`\n${f.code_snippet}\n\`\`\`\n\n`;
        }
        if (f.suggested_patch) {
          md += `**Suggested Remediation:**  \n\`\`\`\n${f.suggested_patch}\n\`\`\`\n\n`;
        }
        md += `---\n\n`;
      });
    }

    md += `\n*Generated by CodeMind AI — Multi-Agent Engineering Review Platform*\n`;
    return md;
  }

  static formatJSON(review: Review, findings: Finding[], counts: SeverityCounts): object {
    return {
      review: {
        id: review.id,
        title: review.title,
        status: review.status,
        language: review.language,
        createdAt: review.created_at,
        completedAt: review.completed_at,
        durationMs: review.duration_ms,
        summary: review.summary,
      },
      severityCounts: counts,
      findingsCount: findings.length,
      findings,
    };
  }
}
